import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const {default:playwright}=await import(pathToFileURL('C:/Users/andyw/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.js'));
const {chromium}=playwright;
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const results=[];
for(const file of ['AKTO-DEEP-RESEARCH.html','HISTORY-REVIEW.html','PAPER-NOTES.html']){
 await page.goto(pathToFileURL(path.join(root,file)).href);
 assert.ok(await page.locator('main h1').count()===1);
 assert.ok(await page.locator('main').innerText());
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 assert.equal(overflow,false);
 results.push({file,heading_count:await page.locator('h2').count(),viewport_overflow:overflow});
}
await page.goto(pathToFileURL(path.join(root,'AKTO-DEEP-RESEARCH.html')).href);
await page.screenshot({path:path.join(root,'evidence/report-preview.png')});
await page.goto(pathToFileURL(path.join(root,'ISSUE-EXPLORER.html')).href);
assert.equal(await page.locator('#rows tr').count(),50);
assert.match(await page.locator('#result').innerText(),/6,928/);
await page.locator('#repo').selectOption('akto');
await page.locator('#query').fill('6309');
assert.equal(await page.locator('#rows tr').count(),1);
assert.match(await page.locator('#rows').innerText(),/merged/);
await page.locator('#reset').click();
await page.locator('#repo').selectOption('tests-library');
await page.locator('#query').fill('228');
assert.equal(await page.locator('#rows tr').count(),1);
assert.match(await page.locator('#rows').innerText(),/pro/);
await page.locator('#reset').click();
await page.locator('#tag').selectOption('pii');
assert.ok(await page.locator('#rows tr').count()>0);
await page.screenshot({path:path.join(root,'evidence/explorer-preview.png')});
await page.locator('#reset').click();
await page.locator('#next').click();
assert.match(await page.locator('#result').innerText(),/51–100/);
await page.locator('#query').fill('no-such-record-zzzz');
assert.equal(await page.locator('#rows tr').count(),0);
assert.equal(await page.locator('#next').isDisabled(),true);
await page.setViewportSize({width:390,height:844});
await page.goto(pathToFileURL(path.join(root,'AKTO-DEEP-RESEARCH.html')).href);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
results.push({file:'ISSUE-EXPLORER.html',checks:['initial_count','core_PR_filter','template_PR_base','PII_filter','pagination','empty_state'],passed:true});
results.push({file:'AKTO-DEEP-RESEARCH.html',mobile_width:390,viewport_overflow:false});
fs.writeFileSync(path.join(root,'evidence/artifact-validation.json'),JSON.stringify({time:new Date().toISOString(),results,page_errors:errors},null,2));
await browser.close();
console.log(JSON.stringify(results));
